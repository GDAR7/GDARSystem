-- ══ CONTROL DE COSTOS · COSTO DIRECTO ══════════════════════════════════════
-- Dos tablas, igual que el Costo Indirecto:
--   presup_c_dir   el presupuesto META. Cada grupo guarda el suyo tal como
--                  figura en el EDP (no se suma desde las filas). La fila con
--                  ítem '0' es la meta total del Costo Directo.
--   valor_c_dir    lo valorizado, una fila por partida y período ('2026-08' =
--                  21/07 al 20/08). La aplicación suma los grupos desde sus filas.
--
-- Los códigos de ítem se renumeraron para que no se repitan y formen árbol.
-- El código original del EDP queda en item_edp.
--
-- Carga inicial desde el EDP N°3 (Agosto) del proyecto EPY-004-26:
--   · 102 filas de presupuesto (81 partidas, grupos y la meta total)
--   · '2026-07' = todo lo valorizado hasta Julio · '2026-08' = Agosto
--   · Además, lo que el EDP DECLARÓ para cada grupo, guardado sobre la fila del
--     grupo (creado_por = 'EDP N°3 declarado'). Es solo referencia: la pantalla
--     lo compara con la suma de las filas y marca con ⚠ lo que no cuadra.
--     En este EDP no cuadran 11 subtotales.
--
-- Se puede correr más de una vez: las filas ya cargadas no se duplican.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.presup_c_dir (
  id           bigint primary key,
  proyecto     text   not null,
  item         text   not null,               -- renumerado: 1 · 1.01 · 1.01.01
  item_edp     text,                          -- código tal como figura en el EDP
  descripcion  text   not null default '',
  unidad       text,
  cantidad     numeric(14,4),
  precio_unit  numeric(16,4),
  total        numeric(16,2),                 -- presupuesto propio de la fila o del grupo
  created_at   timestamptz not null default now(),
  unique (proyecto, item)
);

create table if not exists public.valor_c_dir (
  id           bigint primary key,
  partida_id   bigint not null references public.presup_c_dir(id) on delete cascade,
  periodo      text   not null check (periodo ~ '^[0-9]{4}-[0-9]{2}$'),
  cantidad     numeric(16,4),
  total        numeric(16,2),
  total_manual boolean not null default false,
  creado_por   text,
  created_at   timestamptz not null default now(),
  unique (partida_id, periodo)
);
create index if not exists ix_valor_c_dir_periodo on public.valor_c_dir (periodo);

-- ── Seguridad: igual que las otras tablas (sql/rls_cerrar.sql) ─────────────
alter table public.presup_c_dir enable row level security;
alter table public.valor_c_dir  enable row level security;
drop policy if exists gdar_autenticado on public.presup_c_dir;
drop policy if exists gdar_autenticado on public.valor_c_dir;
create policy gdar_autenticado on public.presup_c_dir
  for all to authenticated using (true) with check (true);
create policy gdar_autenticado on public.valor_c_dir
  for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.presup_c_dir, public.valor_c_dir to authenticated;

