--  NOTA SOBRE SEGURIDAD
--  Este esquema NO usa auth.users ni RLS con auth.uid(), a diferencia del
--  script original. GDARSystem no usa Supabase Auth: el login se resuelve
--  en el navegador contra el arreglo USERS de js/config.js y todas las
--  consultas viajan con la anon key, así que auth.uid() sería siempre NULL
--  y cualquier política basada en él bloquearía el tablero por completo.
--  El control de quién firma cada área se hace en el front (LIB_AREAS +
--  el campo lpAreas de cada usuario) y la trazabilidad queda en lib_bitacora,
--  que registra nombre, cargo y hora de cada cambio de estado.
--  Al final del archivo quedan las políticas RLS listas para el día que se
--  migre a Supabase Auth.
