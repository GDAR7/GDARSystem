-- ---------------------------------------------------------------------
-- 1. Actividades del tablero (una fila = una fila de la matriz)
-- ---------------------------------------------------------------------
create table if not exists lib_actividades (
  id             bigint primary key generated by default as identity,
  proy           text,                    -- código de proyecto (proyectos.codigo)
  frente         text not null default '',
  nombre         text not null default '',
  unidad         text,
  meta           numeric(14,2),
  ejecutor       text,                    -- ECOSERMO / Buenaventura / subcontrata
  semana_inicio  date not null,           -- lunes de la semana del tablero
  wbs_id         bigint,                  -- reservado: enlace futuro con lps_wbs
  cumplio        boolean,                 -- reservado: PPC al cierre de la semana
  causa_no_cump  text,
  creado_por     text,
  created_at     timestamptz not null default now()
);
create index if not exists ix_lib_act_semana on lib_actividades (semana_inicio);

-- ---------------------------------------------------------------------
-- 2. Requisitos / restricciones por área
-- ---------------------------------------------------------------------
create table if not exists lib_requisitos (
  id             bigint primary key generated by default as identity,
  act_id         bigint not null references lib_actividades(id) on delete cascade,
  area           text not null,           -- MAT, EQU, PER, CAL, OFT, SSO, PRO, CLI
  descripcion    text not null default '',
  estado         text not null default 'RES'
                   check (estado in ('RES','PRO','LIB','NA')),
  fecha_comp     date,                    -- fecha comprometida de liberación
  comentario     text,
  firmado_por    text,                    -- nombre del usuario GDAR que firmó
  firmado_cargo  text,
  firmado_at     timestamptz,
  created_at     timestamptz not null default now()
);
create index if not exists ix_lib_req_act  on lib_requisitos (act_id);
create index if not exists ix_lib_req_area on lib_requisitos (area, estado);

-- ---------------------------------------------------------------------
-- 3. Bitácora de cambios de estado
--    La escribe el front (no hay trigger con auth.uid() disponible).
-- ---------------------------------------------------------------------
create table if not exists lib_bitacora (
  id             bigint primary key generated by default as identity,
  req_id         bigint,
  act_nombre     text,
  area           text,
  descripcion    text,
  estado_de      text,
  estado_a       text,
  usuario        text,
  cargo          text,
  registrado_at  timestamptz not null default now()
);
create index if not exists ix_lib_bit_fecha on lib_bitacora (registrado_at desc);

-- ---------------------------------------------------------------------
-- 4. Vistas de apoyo (Power BI / consultas directas)
-- ---------------------------------------------------------------------
-- Estado calculado de cada actividad:
--   RES si alguna restringida · LIB si todas liberadas · si no PRO
create or replace view v_lib_actividad_estado as
select
  a.*,
  count(r.id) filter (where r.estado <> 'NA') as req_vigentes,
  count(r.id) filter (where r.estado = 'LIB') as req_liberados,
  count(r.id) filter (where r.estado = 'RES') as req_restringidos,
  case
    when count(r.id) filter (where r.estado <> 'NA') = 0 then 'NA'
    when count(r.id) filter (where r.estado = 'RES') > 0 then 'RES'
    when count(r.id) filter (where r.estado = 'LIB')
       = count(r.id) filter (where r.estado <> 'NA')     then 'LIB'
    else 'PRO'
  end as estado
from lib_actividades a
left join lib_requisitos r on r.act_id = a.id
group by a.id;

-- IRR por semana (requisitos liberados sobre requisitos vigentes)
create or replace view v_lib_kpi_semana as
select
  a.semana_inicio,
  count(*)                                  as actividades,
  count(*) filter (where a.estado = 'LIB')  as liberadas,
  count(*) filter (where a.estado = 'RES')  as restringidas,
  round(100.0 * sum(a.req_liberados) / nullif(sum(a.req_vigentes),0), 1) as irr_pct
from v_lib_actividad_estado a
group by a.semana_inicio
order by a.semana_inicio desc;

-- Cuello de botella: qué área traba más frentes
create or replace view v_lib_carga_area as
select r.area,
       count(*) filter (where r.estado = 'RES') as restringidos,
       count(*) filter (where r.estado = 'PRO') as en_proceso,
       count(*) filter (where r.estado = 'LIB') as liberados
from lib_requisitos r
group by r.area
order by restringidos desc;

